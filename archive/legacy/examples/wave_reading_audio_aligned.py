    def direction(self):
        self.speech_origin(4)
        self.clear_stage()
        self.title("波向右，质点此刻向上还是向下？")
        t = ValueTracker(0)
        _, _, p = self.string_world(t, probes=(5,))
        self.add(self.clock(t))
        location = self.put(r"x=5\,\mathrm m", 0, 2.45, size=37, color=PARTICLE)
        prediction = self.label("下一小段时间，左侧的形状会接替到这里", 0, -1.8, 31)
        self.play(FadeIn(location), FadeIn(prediction), run_time=1)
        self.mark("direction_question_ready")
        self.at_audio(17 / 30)
        self.focus_begin("slope_prediction")
        self.at_audio(7.7)
        self.focus_begin("left_shape_arrives")
        self.at_audio(7.9)
        self.focus_end("slope_prediction")
        prior = Dot(p(4.5, model.harmonic(4.5, 0)), fill_color=WAVE, radius=.075)
        height = model.harmonic(4.5, 0)
        shift = Arrow(p(4.5, height), p(5, height), buff=0, fill_color=WAVE, thickness=2.5)
        self.at_audio(8.5)
        self.play(FadeIn(prior), FadeIn(shift), run_time=.4)
        self.mark("left_shape_ready")
        
        self.at_audio(15.3)
        self.focus_end("left_shape_arrives")
        self.at_audio(15.7)
        self.focus_begin("particle_rises")
        self.at_audio(16.4)
        self.advance(t, .5)
        self.mark("direction_shifted")
        self.at_audio(19.5)
        self.play(FadeOut(location), FadeIn(self.label("黄色质点向上；横坐标仍是 5 m", 0, 2.45, 31, PARTICLE)), run_time=.5)
        self.mark("direction_rise_label_ready")
        self.at_audio(21.4)
        self.focus_end("particle_rises")
        self.play(FadeOut(Group(prior, shift)), run_time=.2)
        self.mark("direction_result_ready")
        self.at_audio(21.6)
        self.focus_begin("direction_limit")
        original_slope = polyline([p(x, model.harmonic(x, 0)) for x in np.linspace(4.5, 5.5, 81)], MUTED, 3)
        original_point = Circle(radius=.085).set_stroke(MUTED, 2).move_to(p(5, model.harmonic(5, 0)))
        original_label = self.label("灰线：原来 t = 0", -2.0, 1.85, 26, MUTED, width=3.5)
        compare_question = self.label("空间向右变低，为什么这里却向上？", 0, -1.8, 31)
        self.at_audio(21.6)
        self.play(FadeOut(prediction), FadeIn(compare_question), FadeIn(original_slope),
                  FadeIn(original_point), FadeIn(original_label), run_time=.4)
        self.mark("direction_original_slope_ready")
        self.measure_layout("direction_compare_question", compare_question, (original_slope,))
        self.measure_layout("direction_original_label", original_label, (original_slope,))
        rise = Arrow(p(5.35, model.harmonic(5, 0)), p(5.35, model.harmonic(5, .5)),
                     buff=0, fill_color=PARTICLE, thickness=2.5)
        comparison = self.label("同一位置：位移增大，所以质点随时间向上", 0, -1.8, 31, PARTICLE)
        self.at_audio(26.3)
        self.play(FadeOut(compare_question), FadeIn(comparison), ShowCreation(rise), run_time=.5)
        self.mark("direction_displacement_compare_ready")
        self.measure_layout("direction_displacement_result", comparison, (original_slope,))
        self.finish_chapter(4)
        self.focus_end("direction_limit")

