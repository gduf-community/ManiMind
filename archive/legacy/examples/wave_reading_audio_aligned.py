"""Reading-only retiming of the frozen positive-v002 visual case.

Geometry, display dictionaries and physics remain inherited. These chapter
copies change only holds, reveal timing and measured focus boundaries. The
original audio_offsets/at_audio numbers are not used as new evidence.
Trackers/drivers are scene-local; tear_down writes only the current attempt.
Any source, frozen audio/timing, plan or runtime change invalidates its evidence.
"""

import numpy as np
from manimlib import Arrow, Circle, Dot, FadeIn, FadeOut, Group, Line, ShowCreation, ValueTracker, VGroup

from wave_plain_visual import WaveReadingPlainLesson
from wave_unit_shared import INK, MUTED, PARTICLE, SECOND, WAVE, model, polyline


class WaveReadingAudioAlignedLesson(WaveReadingPlainLesson):
    durations = (27, 32, 47, 46, 38, 44)
    audio_offsets = (3, 4, 4, 6, 4, 4)

    def speech_origin(self, index):
        self._speech_origin = self.cues[index]["start"] + self.audio_offsets[index]

    def at_audio(self, relative_seconds):
        self.until(self._speech_origin + relative_seconds)


    def snapshot(self):
        self.speech_origin(0)
        self.title("同一根绳，两种读法")
        t = ValueTracker(0)
        _, _, p = self.string_world(t)
        self.add(self.clock(t))
        origin = self.label("从这张已建立的波形重新计时：t = 0", 0, 2.45, 30)
        self.play(FadeIn(origin), run_time=1)
        self.mark("reading_origin_ready")
        self.at_audio(.5)
        self.focus_begin("time_origin")
        self.at_audio(4.6)
        self.focus_end("time_origin")
        sample = VGroup(*(Line(p(x, 0), p(x, model.harmonic(x, 0)), color=color, stroke_width=4)
                          for x, color in ((4, PARTICLE), (6, SECOND))))
        question = self.label("同一时刻：4 m 与 6 m 的位移分别是多少？", 0, -1.8, 31)
        self.at_audio(4.6)
        self.play(ShowCreation(sample), FadeIn(question), run_time=.5)
        self.measure_layout("snapshot_read_question", question)
        self.mark("spatial_slice_ready")
        self.at_audio(5.1)
        self.focus_begin("spatial_slice")
        values = Group(self.put(r"y(4\,\mathrm m)=+1\,\mathrm{cm}", -2.8, -1.8, size=32),
                       self.put(r"y(6\,\mathrm m)=-1\,\mathrm{cm}", 2.8, -1.8, size=32))
        self.at_audio(12.1)
        self.play(FadeOut(question), FadeIn(values[0]), run_time=.5)
        self.at_audio(14.1)
        self.play(FadeIn(values[1]), run_time=.4)
        self.mark("snapshot_values_ready")
        self.measure_layout("snapshot_values", values)
        identity_question = self.label("全绳的一张快照，还是一个质点的轨迹？", 0, 2.45, 30)
        self.at_audio(16.1)
        self.play(FadeOut(origin), FadeIn(identity_question), run_time=.5)
        self.mark("snapshot_identity_question_ready")
        self.measure_layout("snapshot_identity_question", identity_question)
        identity = self.label("全绳的空间快照，不是一个质点的运动轨迹", 0, 2.45, 30)
        self.at_audio(19.1)
        self.play(FadeOut(identity_question), FadeIn(identity), run_time=.5)
        self.mark("snapshot_identity_ready")
        self.measure_layout("snapshot_identity_result", identity)
        self.finish_chapter(0)
        self.focus_end("spatial_slice")

